CREATE MATERIALIZED VIEW public."DeckStats" AS
 SELECT gp."DeckUuid" AS "Uuid",
    count(*) AS "Games",
    count(*) FILTER (WHERE (gp."PlayerId" = g."WinnerId")) AS "Wins",
    count(*) FILTER (WHERE ((gp."PlayerId" = g."WinnerId") AND (g."WinReason" = ANY (ARRAY['keys'::text, 'concede'::text])) AND (COALESCE(gp."Turn", 0) >= 3) AND (COALESCE(opp."Keys", 0) = 0))) AS "DominantWins"
   FROM ((public."GamePlayers" gp
     JOIN public."Games" g ON ((g."Id" = gp."GameId")))
     LEFT JOIN public."GamePlayers" opp ON (((opp."GameId" = gp."GameId") AND (opp."PlayerId" <> gp."PlayerId"))))
  WHERE ((gp."DeckUuid" IS NOT NULL) AND (opp."DeckUuid" IS DISTINCT FROM gp."DeckUuid") AND (g."WinnerId" IS NOT NULL) AND (g."FinishedAt" IS NOT NULL) AND (g."GameFormat" IS DISTINCT FROM 'sealed'::text) AND (g."StartedAt" >= (now() - '1 year'::interval)))
  GROUP BY gp."DeckUuid"
  WITH NO DATA;

